/** Represents preset data used by the marketing workspace. */
export interface PresetModel {
  /** The id value. */
  id: string;

  /** The name value. */
  name: string;

  /** The family value. */
  family: string;

  /** The surface value. */
  surface: string;

  /** The description value. */
  description: string;

  /** The requiresFabric value. */
  requiresFabric: boolean;

  /** The width value. */
  width: number;

  /** The height value. */
  height: number;
}
